#!/usr/bin/env python3
"""
gen_secrets.py - build-time secret for the SimpleBus bridge API.

Reads secrets.toml (never committed) and writes sb_secret.h with the
32-byte HMAC key used to sign API requests, responses and events
(docs/API.md, sections 3 and 8).

    [auth]
    key = "<64 hex digits>"

Generate a key with:
    python3 -c "import secrets; print(secrets.token_hex(32))"

The header is only rewritten when its content changes, so an unchanged key
does not trigger a rebuild.
"""

import argparse
import re
import sys

try:
    import tomllib  # Python 3.11+
except ModuleNotFoundError:  # pragma: no cover
    import tomli as tomllib  # pip install tomli

KEY_BYTES = 32


def fail(msg):
    sys.stderr.write(
        f"gen_secrets: {msg}\n"
        "  See docs/API.md section 8. Create secrets.toml from "
        "secrets.example.toml with a fresh key:\n"
        '    python3 -c "import secrets; print(secrets.token_hex(32))"\n'
    )
    sys.exit(1)


def load_key(path):
    try:
        with open(path, "rb") as f:
            data = tomllib.load(f)
    except FileNotFoundError:
        fail(f"{path} not found")
    except tomllib.TOMLDecodeError as e:
        fail(f"{path}: {e}")

    key = data.get("auth", {}).get("key")
    if not isinstance(key, str):
        fail(f"{path}: missing [auth] key")
    if not re.fullmatch(r"[0-9a-fA-F]{%d}" % (2 * KEY_BYTES), key):
        fail(f"{path}: [auth] key must be exactly {2 * KEY_BYTES} hex digits "
             f"({KEY_BYTES} bytes)")

    raw = bytes.fromhex(key)
    if len(set(raw)) < 8:
        fail(f"{path}: [auth] key looks like a placeholder, not random")
    return raw


def render(raw, src):
    rows = []
    for i in range(0, len(raw), 8):
        rows.append("    " + ", ".join(f"0x{b:02X}" for b in raw[i:i + 8]) + ",")
    body = "\n".join(rows)
    return f"""/*
 * sb_secret.h - GENERATED by cmake/gen_secrets.py from {src}.
 * Do not edit, do not commit. Contains the API HMAC key.
 */
#ifndef SB_SECRET_H
#define SB_SECRET_H

#include <stdint.h>

#define SB_SECRET_KEY_LEN {len(raw)}u

static const uint8_t sb_secret_key[SB_SECRET_KEY_LEN] = {{
{body}
}};

#endif /* SB_SECRET_H */
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--secrets", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    text = render(load_key(args.secrets), "secrets.toml")

    try:
        with open(args.out, "r", encoding="utf-8") as f:
            if f.read() == text:
                return
    except FileNotFoundError:
        pass
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main()
